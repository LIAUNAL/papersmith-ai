def _help_door(command: str):
    """Run ``<command> --help`` and return ``(exit code, printed help)``."""
    buffer = io.StringIO()
    try:
        with contextlib.redirect_stdout(buffer):
            main([command, "--help"])
    except SystemExit as exc:
        return exc.code, buffer.getvalue()
    raise AssertionError(f"{command} --help did not exit through SystemExit")


class CommandRosterTests(unittest.TestCase):
    """Every advertised command answers its own front door."""

    def test_every_command_has_a_working_help_door(self) -> None:
        for command in COMMANDS:
            with self.subTest(command=command):
                code, text = _help_door(command)
                self.assertEqual(code, 0, f"{command} --help must exit 0")
                self.assertIn("usage:", text, f"{command} printed no usage")

    def test_version_is_a_top_level_flag(self) -> None:
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            with self.assertRaises(SystemExit) as caught:
                main(["--version"])
        self.assertEqual(caught.exception.code, 0)
        self.assertIn("papersmith", buffer.getvalue())


