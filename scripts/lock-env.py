#!/usr/bin/env python3
"""Refresh the locked environments built from ``env/environment.yml`` (issue #58).

Maintainer-only: it needs ``conda-lock`` and network access, which a workspace
never does. ``scripts/setup_env.py install`` reads the locks this writes; it
never solves the source files itself.

    python3 scripts/lock-env.py lock [--variant cpu|cuda|rocm ...] [--conda-lock <path>] [--micromamba <path>]
    python3 scripts/lock-env.py requirements
    python3 scripts/lock-env.py check [--root <checkout>]

``lock`` solves each variant for its platforms and records, in
``env/locks.json``, the sha256 of every source file it was solved from.
``requirements`` writes ``requirements.txt`` from the sources (pip names, the
same bounds). ``check`` exits 1 when a source changed since its lock was
written, when a lock names other platforms than ``env/locks.json`` records, or
when ``requirements.txt`` is not what ``requirements`` writes, so an edit to
``env/*`` without a refresh fails the suite (tests/test_env_locks.py).
The procedure is in docs/releasing.md ("Refreshing the dependency locks").
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from papersmith.core import manifest  # noqa: E402  (one reader of env/*.yml for every consumer)

#: The CUDA version the cuda variant is solved for: builds for it run on any
#: NVIDIA driver from the 570 series on. The other variants are solved without CUDA,
#: so no package resolves to a CUDA build there.
CUDA_VERSION = "12.8"

#: variant -> (source files, platforms). The ROCm variant locks no torch: it comes
#: from AMD's pinned index (skills/_core/gpu/gpu_probe.py). Ingestion's pip layer
#: (env/ingestion.txt) is installed on top of every variant and is not locked here.
VARIANTS: dict[str, tuple[tuple[str, ...], tuple[str, ...]]] = {
    "cpu": (("environment.yml", "torch-cpu.yml"), ("linux-64", "osx-64", "osx-arm64", "win-64")),
    "cuda": (("environment.yml", "torch-cuda.yml"), ("linux-64", "win-64")),
    "rocm": (("environment.yml",), ("linux-64",)),
}


#: The files ``requirements`` writes requirements.txt from, in this order.
REQUIREMENTS_SOURCES = ("environment.yml", "torch-cpu.yml", "ingestion.txt")

#: Comment lines written under a requirement, by pip name.
REQUIREMENT_NOTES = {
    "kagglesdk": (
        "published standalone since 2025-07-11; NOT vendored inside the `kaggle` CLI",
        "distribution. `adapters/kaggle_driver.py` is the only file in remote-execution",
        "permitted to import it; kagglesdk/kaggle_http_client.py:14-17 documents its",
        "Bearer-auth path as mid-migration (\"This was created from kaggle_api_client.py,",
        "prior to recent changes to auth handling. The new client requires",
        "KAGGLE_API_TOKEN, so it is not currently usable by the CLI.\") -- pinned at the",
        "version this was measured against; a drift is locked by DoctrinePinTests in",
        "tests/test_remote_execution.py.",
    ),
}

REQUIREMENTS_HEADER = """\
# GENERATED by `python3 scripts/lock-env.py requirements` from env/environment.yml,
# env/torch-cpu.yml and env/ingestion.txt. Do not edit it: edit those sources,
# refresh the locks and regenerate it (docs/releasing.md); `python3
# scripts/lock-env.py check` fails while it differs.
#
# Nothing installs from this file: scripts/setup_env.py builds the environment
# from env/*.conda-lock.yml, and `smith ui` derives its venv from
# env/environment.yml. It states the forge's runtime (Python >=3.11) for a pip
# user, in pip names (conda-forge's pytorch-cpu is torch here), and the pin
# tests read it (tests/test_env_pins.py, DoctrinePinTests).
"""

REQUIREMENTS_FOOTER = """\

# Deliberately NOT here. Optuna and matplotlib are TARGET-side dependencies:
# `hyperparameter-search report` runs under the target's own `.venv`
# interpreter (or `--python`), so they are installed in the target's venv.
# The Colab CLI (`google-colab-cli`, pinned by `PINNED_VERSION` in
# `src/papersmith/core/colab.py`) is a `uv tool` on `PATH`, not a Python
# dependency of this environment.
"""


def lock_path(env: Path, variant: str) -> Path:
    # micromamba reads a file as a conda-lock lockfile only when its name ends in `-lock.yml`.
    return env / f"{variant}.conda-lock.yml"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inputs(env: Path, variant: str) -> dict[str, str]:
    return {name: sha256(env / name) for name in VARIANTS[variant][0]}


def read_record(env: Path) -> dict:
    try:
        data = json.loads((env / "locks.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"schema": 1, "variants": {}}
    return data if isinstance(data, dict) and isinstance(data.get("variants"), dict) else {"schema": 1, "variants": {}}


def lock_platforms(lock: Path) -> list[str]:
    """The platforms a conda-lock file's ``metadata.platforms`` names."""
    lines = lock.read_text(encoding="utf-8").splitlines()
    try:
        start = lines.index("  platforms:", lines.index("metadata:")) + 1
    except ValueError:
        return []
    platforms = []
    for line in lines[start:]:
        if not line.startswith("  - "):
            break
        platforms.append(line[4:].strip())
    return platforms


def requirements_text(env: Path) -> str:
    """requirements.txt as ``requirements`` writes it from ``env``."""
    blocks = []
    for name in REQUIREMENTS_SOURCES:
        lines = [f"# env/{name}"]
        if name.endswith(".yml"):
            for conda, constraint, comment in manifest.conda_dependencies(env / name):
                requirement = manifest.pip_requirement(conda, constraint)
                if requirement is None:
                    continue
                lines.append(f"{requirement}  # {comment}" if comment else requirement)
                pip_name = manifest.PIP_DISTRIBUTIONS.get(conda, conda)
                lines.extend(f"# {note}" for note in REQUIREMENT_NOTES.get(pip_name, ()))
        else:
            for line in (env / name).read_text(encoding="utf-8").splitlines():
                if line.strip() and not line.lstrip().startswith("#"):
                    lines.append(line.strip())
        blocks.append("\n".join(lines) + "\n")
    return REQUIREMENTS_HEADER + "\n" + "\n".join(blocks) + REQUIREMENTS_FOOTER


def stale(root: Path) -> list[str]:
    """One line per lock missing, older than its sources or for other platforms,
    and one when requirements.txt is not what ``requirements`` writes."""
    env = root / "env"
    record = read_record(env)
    problems = []
    for variant, (_, platforms) in VARIANTS.items():
        entry = record["variants"].get(variant)
        lock = lock_path(env, variant)
        if not lock.is_file():
            problems.append(f"{variant}: env/{lock.name} is missing")
        elif not isinstance(entry, dict) or entry.get("inputs") != inputs(env, variant):
            problems.append(f"{variant}: env/* changed since its lock; run `python3 scripts/lock-env.py lock "
                            f"--variant {variant}`")
        elif entry.get("platforms") != list(platforms) or lock_platforms(lock) != list(platforms):
            problems.append(f"{variant}: locked for {lock_platforms(lock)} (env/locks.json: "
                            f"{entry.get('platforms')}), expected {list(platforms)}")
    try:
        current = (root / "requirements.txt").read_text(encoding="utf-8")
    except OSError:
        current = None
    if current != requirements_text(env):
        problems.append("requirements.txt is not generated from env/*; run "
                        "`python3 scripts/lock-env.py requirements`")
    return problems


def cmd_lock(args: argparse.Namespace) -> int:
    conda_lock = args.conda_lock or shutil.which("conda-lock")
    if not conda_lock:
        print("conda-lock is not on PATH; pass --conda-lock <path> (docs/releasing.md)", file=sys.stderr)
        return 2
    env = Path(args.root) / "env"
    record = read_record(env)
    for variant in args.variant or list(VARIANTS):
        files, platforms = VARIANTS[variant]
        command = [conda_lock, "lock", "--lockfile", str(lock_path(env, variant))]
        if args.micromamba:
            command += ["--micromamba", "--conda", args.micromamba]
        for name in files:
            command += ["-f", str(env / name)]
        for platform in platforms:
            command += ["-p", platform]
        command += ["--with-cuda", CUDA_VERSION] if variant == "cuda" else ["--without-cuda"]
        print(f"locking {variant} for {', '.join(platforms)}", flush=True)
        if subprocess.run(command, cwd=env).returncode != 0:
            print(f"conda-lock failed for {variant}; its previous lock is kept", file=sys.stderr)
            return 1
        record["variants"][variant] = {"inputs": inputs(env, variant), "platforms": list(platforms),
                                       "lockfile": lock_path(env, variant).name,
                                       "cuda": CUDA_VERSION if variant == "cuda" else None}
        (env / "locks.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return 0


def cmd_requirements(args: argparse.Namespace) -> int:
    target = Path(args.root) / "requirements.txt"
    target.write_text(requirements_text(Path(args.root) / "env"), encoding="utf-8")
    print(f"wrote {target}")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    problems = stale(Path(args.root))
    for line in problems:
        print(line)
    if not problems:
        print("locks: current")
    return 1 if problems else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="lock-env.py", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="verb", required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", default=str(ROOT),
                        help="the checkout whose env/ and requirements.txt to use (default: this one)")
    lock = sub.add_parser("lock", parents=[common], help="solve the locks with conda-lock")
    lock.add_argument("--variant", action="append", choices=list(VARIANTS))
    lock.add_argument("--conda-lock", default=None, help="path to the conda-lock executable")
    lock.add_argument("--micromamba", default=None, help="solve with this micromamba binary")
    lock.set_defaults(func=cmd_lock)
    requirements = sub.add_parser("requirements", parents=[common],
                                  help="write requirements.txt from the sources")
    requirements.set_defaults(func=cmd_requirements)
    check = sub.add_parser("check", parents=[common],
                           help="exit 1 when a lock or requirements.txt is older than its sources")
    check.set_defaults(func=cmd_check)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
